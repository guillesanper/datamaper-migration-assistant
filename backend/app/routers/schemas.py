@router.post(
    "/api/projects/{project_id}/schemas/columns/{column_id}/validate-type-change",
    tags=["schemas-api"],
)
async def api_validate_type_change(
    project_id: str,
    column_id: str,
    new_type: str = Body(..., embed=True),
    db=Depends(get_db_session),
    current_user=Depends(get_current_user),
):
    """
    Validate a data type change for a column (API endpoint)

    Returns:
        - is_safe: bool indicating if the change is safe
        - risk_level: 'safe' | 'warning' | 'danger'
        - message: description of the risk
        - recommendation: what to do
        - requires_confirmation: if user confirmation is needed
        - requires_backup: if backup is needed before change
    """
    try:
        # Get column and table info
        row = (
            db.execute(
                text("""
                SELECT c.id, c.table_id, t.project_id
                FROM columns c
                JOIN tables t ON c.table_id = t.id
                WHERE c.id = :column_id
            """),
                {"column_id": column_id},
            )
            .mappings()
            .fetchone()
        )

        if not row:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND, detail=make_error(ErrorCode.COLUMN_NOT_FOUND)
            )

        column = dict(row)

        # Check permissions
        SchemaService.can_user_modify_schema(db, column["project_id"], current_user["id"])

        # Validate type change
        validation = TypeCompatibilityService.validate_type_change_request(
            db, table_id=column["table_id"], column_id=column_id, new_type=new_type
        )

        return {"status": "success", "validation": validation, "message": validation["message"]}

    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=make_error(ErrorCode.SCHEMA_OPERATION_FAILED),
        )


