export interface Table {
  id: string;
  project_id: string;
  name: string;
  type: 'origin' | 'destination';
  created_at: string;
  updated_at: string;
  // Campos para modo connector (no se guarda en BD local)
  is_connector?: boolean;
  table_hash?: string;
  session_id?: string;
}

export interface Column {
  id: string;
  table_id: string;
  name: string;
  data_type: DataType;
  table_type: 'origin' | 'destination';
  is_nullable: boolean;
  is_primary: boolean;
  is_autogenerated?: boolean;
  created_at: string;
  updated_at: string;
  // Campos para modo connector (no se guarda en BD local)
  column_hash?: string;
}

