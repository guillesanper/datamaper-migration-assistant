"""
Endpoints de schemas con {project_id} y el id de una tabla/columna de OTRO proyecto.

Los permisos se comprobaban contra el project_id de la ruta: con acceso a un proyecto
se leían o modificaban tablas y columnas ajenas.
"""

import uuid

import pytest
from sqlalchemy import text


@pytest.fixture
def foreign_table(db_session):
    """Tabla y columna en un proyecto de otro usuario."""
    from app.crud.project_crud import ProjectCRUD
    from app.services.auth_service import AuthService

    suffix = uuid.uuid4().hex[:10]
    other = AuthService(db_session).create_user(
        username=f"other_{suffix}", email=f"other_{suffix}@example.com", password="Str0ng!Pass1"
    )
    project = ProjectCRUD.create_project_orm(
        db=db_session,
        owner_id=other["user_id"],
        name="Foreign",
        description="",
        origin_db="PostgreSQL",
        destination_db="PostgreSQL",
        status="active",
    )
    table_id, column_id = str(uuid.uuid4()), str(uuid.uuid4())
    db_session.execute(
        text(
            "INSERT INTO tables (id, project_id, name, type, is_encrypted)"
            " VALUES (:id, :p, 'secret_salaries', 'origin', false)"
        ),
        {"id": table_id, "p": str(project["id"])},
    )
    db_session.execute(
        text(
            "INSERT INTO columns (id, table_id, name, data_type, table_type, is_encrypted,"
            " is_nullable, is_primary, is_autogenerated)"
            " VALUES (:id, :t, 'salary', 'INTEGER', 'origin', false, true, false, false)"
        ),
        {"id": column_id, "t": table_id},
    )
    db_session.commit()
    return {"table_id": table_id, "column_id": column_id}


def _table_name(db_session, table_id):
    db_session.expire_all()
    return db_session.execute(
        text("SELECT name FROM tables WHERE id = :id"), {"id": table_id}
    ).scalar()


def test_cannot_read_foreign_table(authenticated_client, test_project, foreign_table):
    response = authenticated_client.get(
        f"/api/projects/{test_project['id']}/schemas/tables/{foreign_table['table_id']}"
    )

    assert response.status_code == 404
    assert "secret_salaries" not in response.text


def test_cannot_rename_foreign_table(authenticated_client, test_project, foreign_table, db_session):
    response = authenticated_client.put(
        f"/api/projects/{test_project['id']}/schemas/tables/{foreign_table['table_id']}",
        json={"name": "pwned"},
    )

    assert response.status_code == 404
    assert _table_name(db_session, foreign_table["table_id"]) == "secret_salaries"


def test_cannot_delete_foreign_table(authenticated_client, test_project, foreign_table, db_session):
    response = authenticated_client.delete(
        f"/api/projects/{test_project['id']}/schemas/tables/{foreign_table['table_id']}"
    )

    assert response.status_code == 404
    assert _table_name(db_session, foreign_table["table_id"]) == "secret_salaries"


def test_cannot_read_or_change_foreign_column(authenticated_client, test_project, foreign_table):
    base = f"/api/projects/{test_project['id']}/schemas/columns/{foreign_table['column_id']}"

    assert authenticated_client.get(base).status_code == 404
    assert authenticated_client.delete(base).status_code == 404


def test_own_table_still_accessible(authenticated_client, test_project, db_session):
    table_id = str(uuid.uuid4())
    db_session.execute(
        text(
            "INSERT INTO tables (id, project_id, name, type, is_encrypted)"
            " VALUES (:id, :p, 'mine', 'origin', false)"
        ),
        {"id": table_id, "p": str(test_project["id"])},
    )
    db_session.commit()

    response = authenticated_client.get(
        f"/api/projects/{test_project['id']}/schemas/tables/{table_id}"
    )

    assert response.status_code == 200, response.text
    assert response.json()["table"]["name"] == "mine"
