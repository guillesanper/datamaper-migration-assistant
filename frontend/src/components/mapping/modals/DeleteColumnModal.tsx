// src/components/mapping/modals/DeleteColumnModal.tsx
import React, { useState } from 'react';
import { X, AlertTriangle, Columns } from 'lucide-react';
import { useTranslation } from 'react-i18next';
import { mappingService } from '../../../services/mapping_service';
import { toast } from '../../../utils/toast';
import type { Column } from '../../../types/mapping-types';
import styles from '../../../styles/mapping/mapping.module.css';

interface DeleteColumnModalProps {
  isOpen: boolean;
  onClose: () => void;
  projectId: string;
  column: Column | null;
  tableName: string;
  onSuccess: () => void;
}

export const DeleteColumnModal: React.FC<DeleteColumnModalProps> = ({
  isOpen,
  onClose,
  projectId,
  column,
  tableName,
  onSuccess
}) => {
  const { t } = useTranslation(['mapping', 'common']);
  const [isDeleting, setIsDeleting] = useState(false);

  const handleDelete = async () => {
    if (!column) return;

    setIsDeleting(true);

    try {
      const result = await mappingService.deleteColumn(projectId, column.id);
      toast.success(t('mapping:deleteColumn.toast.success', { mappings: result.mappings_deleted }));
      onSuccess();
      onClose();
    } catch (err: unknown) {
      console.error('Error al eliminar columna:', err);
      const errObj = err as Record<string, unknown>;
      const responseDetail = (errObj.response as Record<string, unknown> | undefined)?.data as Record<string, unknown> | undefined;
      const errorMessage = String(responseDetail?.detail ?? '') || (err instanceof Error ? err.message : '') || t('mapping:deleteColumn.toast.error');
      toast.error(errorMessage);
    } finally {
      setIsDeleting(false);
    }
  };

  if (!isOpen || !column) return null;

  return (
    <div className={styles.modalOverlay}>
      <div className={styles.modalContent} style={{ maxWidth: '500px' }}>
        {/* Header */}
        <div className={styles.modalHeader}>
          <div className="flex items-center gap-2">
            <AlertTriangle className="w-5 h-5 text-red-500" />
            <h2 className={styles.modalTitle}>{t('mapping:deleteColumn.title')}</h2>
          </div>
          <button onClick={onClose} className={styles.modalCloseButton} disabled={isDeleting}>
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Content */}
        <div className={styles.modalBody}>
          <div className="space-y-4">
            {/* Column info */}
            <div className="bg-muted p-4 rounded-lg border-l-4 border-l-red-500">
              <div className="flex items-center gap-3">
                <Columns className="w-6 h-6 text-muted-foreground" />
                <div>
                  <p className="font-semibold">{column.name}</p>
                  <p className="text-sm text-muted-foreground">
                    {t('mapping:deleteColumn.info', { table: tableName, type: column.data_type || 'N/A' })}
                  </p>
                  <div className="flex gap-2 mt-1">
                    {column.is_primary && (
                      <span className="text-xs px-2 py-0.5 rounded bg-yellow-100 text-yellow-700 dark:bg-yellow-900/30 dark:text-yellow-400">
                        Primary Key
                      </span>
                    )}
                    {!column.is_nullable && (
                      <span className="text-xs px-2 py-0.5 rounded bg-red-100 text-red-700 dark:bg-red-900/30 dark:text-red-400">
                        NOT NULL
                      </span>
                    )}
                    {column.is_autogenerated && (
                      <span className="text-xs px-2 py-0.5 rounded bg-purple-100 text-purple-700 dark:bg-purple-900/30 dark:text-purple-400">
                        {t('mapping:columnModal.autogenerated.label')}
                      </span>
                    )}
                  </div>
                </div>
              </div>
            </div>

            {/* Warning */}
            <div className="bg-red-50 dark:bg-red-900/20 border border-red-200 dark:border-red-800 rounded-lg p-4">
              <div className="flex gap-3">
                <AlertTriangle className="w-5 h-5 text-red-600 dark:text-red-400 flex-shrink-0 mt-0.5" />
                <div className="space-y-2">
                  <p className="text-sm font-semibold text-red-900 dark:text-red-100">
                    {t('mapping:deleteTable.irreversible')}
                  </p>
                  <ul className="text-sm text-red-800 dark:text-red-200 space-y-1 list-disc list-inside">
                    <li>{t('mapping:deleteColumn.consequence1')}</li>
                    <li>{t('mapping:deleteTable.consequence3')}</li>
                  </ul>
                </div>
              </div>
            </div>

            {/* Confirmation */}
            <p className="text-sm text-muted-foreground">
              {t('mapping:deleteColumn.warning', { name: column.name, table: tableName })}
            </p>
          </div>
        </div>

        {/* Footer */}
        <div className={styles.modalFooter}>
          <div className={styles.modalFooterRight}>
            <button
              onClick={onClose}
              className={styles.toolbarButton}
              disabled={isDeleting}
            >
              {t('common:actions.cancel')}
            </button>
            <button
              onClick={handleDelete}
              disabled={isDeleting}
              className="px-4 py-2 bg-red-600 hover:bg-red-700 text-white rounded-lg flex items-center gap-2 transition-colors disabled:opacity-50 disabled:cursor-not-allowed"
            >
              {isDeleting ? (
                <>
                  <div className="animate-spin rounded-full h-4 w-4 border-2 border-white border-t-transparent" />
                  {t('mapping:deleteColumn.deletingBtn')}
                </>
              ) : (
                <>
                  <AlertTriangle className="w-4 h-4" />
                  {t('mapping:deleteColumn.submitBtn')}
                </>
              )}
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
