from utilities.migrations.validators import BackupManager, MigrationValidator


@pytest.fixture
def column_ids(db_session, test_project):
    """Tabla con una columna, para MigrationValidator."""
    table = Table(
        id=uuid.uuid4(),
        project_id=test_project["id"],
        name="validator_table",
        type="origin",
        is_encrypted=False,
    )
    db_session.add(table)
    db_session.flush()
    column = TableColumn(
        id=uuid.uuid4(),
        table_id=table.id,
        name="validator_col",
        data_type="TEXT",
        table_type="origin",
        is_encrypted=False,
        is_nullable=True,
        is_primary=False,
        is_autogenerated=False,
    )
    db_session.add(column)
    db_session.commit()
    return str(table.id), str(column.id)


@pytest.mark.integration
class TestExecutionRecords:
    def test_create_update_and_read_execution_record(self, db_session, test_project, test_user):
        service = ExecutionService()
        project_id = test_project["id"]

        execution_id = service._create_execution_record(
            db_connection=db_session,
            project_id=project_id,
            script="SELECT 1;",
            user_id=test_user["id"],
        )
        assert uuid.UUID(execution_id)

        running = service.get_execution_status(db_session, execution_id)
        assert running["execution_id"] == execution_id
        assert running["status"] == "running"
        assert running["progress_percent"] == 0
        assert running["current_step"] == "Initializing..."
        assert running["started_at"] is not None
        assert running["completed_at"] is None

        service._update_execution_record(
            db_connection=db_session,
            execution_id=execution_id,
            status="success",
            rows_migrated=42,
            backup_id="backup_20250101_000000",
            execution_log=[{"step": 1, "table": "customers", "status": "success"}],
        )

        done = service.get_execution_status(db_session, execution_id)
        assert done["status"] == "success"
        assert done["progress_percent"] == 100
        assert done["rows_migrated"] == 42
        assert done["current_step"] == "Step 1: customers"
        assert done["completed_at"] is not None
        assert done["error_message"] is None

    def test_update_stores_error_message(self, db_session, test_project, test_user):
        service = ExecutionService()
        execution_id = service._create_execution_record(
            db_connection=db_session,
            project_id=test_project["id"],
            script="SELECT 1;",
            user_id=None,
        )
        service._update_execution_record(
            db_connection=db_session,
            execution_id=execution_id,
            status="failed",
            error_message="boom",
        )
        status = service.get_execution_status(db_session, execution_id)
        assert status["status"] == "failed"
        assert status["error_message"] == "boom"
        assert status["rows_migrated"] == 0

    def test_get_status_of_unknown_execution_raises(self, db_session):
        with pytest.raises(ExecutionServiceError):
            ExecutionService().get_execution_status(db_session, str(uuid.uuid4()))


@pytest.mark.integration
class TestBackupManagerDb:
    def test_create_backup_writes_table_rows(self, db_session, test_project, tmp_path):
        manager = BackupManager(db_session, backup_dir=str(tmp_path))

        info = manager.create_backup(["projects"], description="test")

        assert info["tables"][0]["table"] == "projects"
        assert info["tables"][0]["row_count"] >= 1
        backup_file = tmp_path / info["tables"][0]["file"]
        data = json.loads(backup_file.read_text(encoding="utf-8"))
        assert data["row_count"] == info["tables"][0]["row_count"]
        assert str(test_project["id"]) in {row["id"] for row in data["data"]}
        assert (tmp_path / f"{info['backup_id']}_metadata.json").exists()


@pytest.mark.integration
class TestMigrationValidatorDb:
    def test_analyze_data_for_known_column(self, db_session, column_ids):
        table_id, column_id = column_ids

        result = MigrationValidator(db_session).analyze_data_for_type_change(
            table_id, column_id, "VARCHAR(10)"
        )

        assert result["is_safe_data"] is True
        assert "10" in result["message"]

    def test_analyze_data_for_unknown_column(self, db_session):
        result = MigrationValidator(db_session).analyze_data_for_type_change(
            str(uuid.uuid4()), str(uuid.uuid4()), "VARCHAR(10)"
        )

        assert result["message"] == "Columna no encontrada"
