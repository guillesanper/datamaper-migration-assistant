def _add_table(db_session, project_id, name, table_type, columns):
    """Crea una tabla con sus columnas: columns = [(nombre, tipo, is_primary, is_nullable)]"""
    table = Table(
        id=uuid.uuid4(),
        project_id=project_id,
        name=name,
        type=table_type,
        is_encrypted=False,
    )
    db_session.add(table)
    db_session.flush()
    for cname, ctype, is_pk, is_null in columns:
        db_session.add(
            TableColumn(
                id=uuid.uuid4(),
                table_id=table.id,
                name=cname,
                data_type=ctype,
                table_type=table_type,
                is_encrypted=False,
                is_nullable=is_null,
                is_primary=is_pk,
                is_autogenerated=False,
            )
        )
    db_session.commit()
    return table


