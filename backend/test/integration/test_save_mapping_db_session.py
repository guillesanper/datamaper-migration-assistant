@pytest.mark.integration
def test_save_mapping_uses_orm_session_not_psycopg2(authenticated_client, project_with_schema):
    """
    Regression test: POST /api/mappings/projects/{project_id}/save must not fail
    with AttributeError when calling ORM functions.

    Before fix: save_mapping passed a raw psycopg2 connection to ORM functions
                → AttributeError: 'psycopg2.extensions.connection' has no attribute 'query'
    After fix:  save_mapping injects a separate SQLAlchemy Session (db_orm) for ORM calls.
    """
    schema = project_with_schema
    project_id = schema["project_id"]

    response = authenticated_client.post(
        f"/api/mappings/projects/{project_id}/save",
        json={
            "origin_table": schema["origin_table"],
            "origin_column": schema["origin_column"],
            "destination_table": schema["destination_table"],
            "destination_column": schema["destination_column"],
        },
    )

    # Must not be 500 (which would indicate the AttributeError)
    assert response.status_code != 500, (
        f"Got 500 — likely the ORM session bug is still present. " f"Response: {response.json()}"
    )
    assert (
        response.status_code == 200
    ), f"Expected 200, got {response.status_code}. Response: {response.json()}"
    assert response.json().get("status") == "ok"


@pytest.mark.integration
def test_delete_mapping_uses_orm_session_not_psycopg2(authenticated_client, project_with_schema):
    """
    Regression test: DELETE /api/mappings/projects/{project_id}/delete must not fail
    with NameError/AttributeError when calling ORM functions.

    Before fix: delete_mapping passed raw psycopg2 connection to ORM functions,
                and accidentally referenced undefined db_orm variable.
    After fix:  delete_mapping injects db_orm=Depends(get_db_session) for ORM calls.
    """
    schema = project_with_schema
    project_id = schema["project_id"]
    payload = {
        "origin_table": schema["origin_table"],
        "origin_column": schema["origin_column"],
        "destination_table": schema["destination_table"],
        "destination_column": schema["destination_column"],
    }

    # First create a mapping to delete
    r_create = authenticated_client.post(f"/api/mappings/projects/{project_id}/save", json=payload)
    assert r_create.status_code == 200, f"Setup failed (save): {r_create.json()}"

    # Now delete it — must not 500
    r_delete = authenticated_client.request(
        "DELETE",
        f"/api/mappings/projects/{project_id}/delete",
        json=payload,
    )
    assert r_delete.status_code != 500, (
        f"Got 500 — likely the ORM session bug is still present in delete_mapping. "
        f"Response: {r_delete.json()}"
    )
    assert (
        r_delete.status_code == 200
    ), f"Expected 200, got {r_delete.status_code}. Response: {r_delete.json()}"


@pytest.mark.integration
def test_save_mapping_duplicate_returns_400(authenticated_client, project_with_schema):
    """
    After a mapping is created, creating the same one again must return 400 (duplicate),
    not 500. This verifies ORM duplicate-check also uses the correct session.
    """
    schema = project_with_schema
    project_id = schema["project_id"]
    payload = {
        "origin_table": schema["origin_table"],
        "origin_column": schema["origin_column"],
        "destination_table": schema["destination_table"],
        "destination_column": schema["destination_column"],
    }

    # First creation: must succeed
    r1 = authenticated_client.post(f"/api/mappings/projects/{project_id}/save", json=payload)
    assert r1.status_code == 200, f"First save failed: {r1.json()}"

    # Second creation: must be rejected as duplicate (400), not crash (500)
    r2 = authenticated_client.post(f"/api/mappings/projects/{project_id}/save", json=payload)
    assert (
        r2.status_code == 400
    ), f"Expected 400 (duplicate), got {r2.status_code}. Response: {r2.json()}"
