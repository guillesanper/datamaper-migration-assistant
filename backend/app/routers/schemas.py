@router.post("/api/projects/{project_id}/schemas/tables", tags=["schemas-api"])
async def api_create_table(
    project_id: str,  #  ADDED: from path
    table_request: CreateTableRequest,
    request: Request,
    db=Depends(get_db_session),
    current_user=Depends(get_current_user),
    _=Depends(validate_encryption_session),
):
    """Create a new table (API endpoint)"""
    try:
        #  Get encryption key from session (injected by middleware)
        encryption_key = getattr(request.state, "encryption_key", None)

        table = SchemaService.create_table_with_validation(
            db,
            project_id,  #  From path
            current_user["id"],
            table_request.name,
            table_request.type,
            encryption_key,
        )

        # CREATE VERSION ENTRY
        try:
            from app.services import version_control_service

            rows = (
                db.execute(
                    text(
                        "SELECT id, name, type, created_at, updated_at"
                        " FROM tables WHERE project_id = :project_id ORDER BY type, name"
                    ),
                    {"project_id": project_id},
                )
                .mappings()
                .fetchall()
            )
            all_tables = [dict(r) for r in rows]

            version_control_service.create_version(
                db=db,
                project_id=project_id,
                entity_id=table["id"],
                entity_type="table",
                user_id=current_user["id"],
                change_type="create",
                snapshot={
                    "tables": all_tables,
                    "table_added": {
                        "id": table["id"],
                        "name": table["name"],
                        "type": table["type"],
                    },
                },
                message=f"Table created: {table['name']} ({table['type']})",
            )
        except Exception as e:
            print(f"[WARNING] Failed to create version for table creation: {str(e)}")

        await realtime_broadcast(
            project_id,
            {
                "type": "table_added",
                "ts": datetime.now(timezone.utc).isoformat(),
                "actor_id": str(current_user["id"]),
                "table": {"id": table["id"], "name": table["name"], "type": table["type"]},
            },
        )

        return {"status": "success", "message": "Tabla creada exitosamente", "table": table}
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=make_error(ErrorCode.SCHEMA_OPERATION_FAILED),
        )


@router.put("/api/projects/{project_id}/schemas/tables/{table_id}", tags=["schemas-api"])
async def api_update_table(
    project_id: str,
    table_id: str,
    update_request: UpdateTableRequest,
    request: Request,
    db=Depends(get_db_session),
    current_user=Depends(get_current_user),
    _=Depends(validate_encryption_session),
):
    """Update a table (API endpoint)"""
    ensure_table_in_project(db, project_id, table_id)
    try:
        #  Get encryption key from session
        encryption_key = getattr(request.state, "encryption_key", None)

        from app.crud import schemas_crud

        old_table = schemas_crud.get_table_by_id_orm(db, table_id, encryption_key)

        table = SchemaService.update_table_with_validation(
            db, table_id, current_user["id"], update_request.name, encryption_key
        )
        assert table is not None

        # CREATE VERSION ENTRY
        try:
            from app.services import version_control_service

            rows = (
                db.execute(
                    text(
                        "SELECT id, name, type, created_at, updated_at"
                        " FROM tables WHERE project_id = :project_id ORDER BY type, name"
                    ),
                    {"project_id": project_id},
                )
                .mappings()
                .fetchall()
            )
            all_tables = [dict(r) for r in rows]

            version_control_service.create_version(
                db=db,
                project_id=project_id,
                entity_id=table_id,
                entity_type="table",
                user_id=current_user["id"],
                change_type="update",
                snapshot={
                    "tables": all_tables,
                    "table_updated": {
                        "id": table_id,
                        "old_name": old_table["name"] if old_table else None,
                        "new_name": table["name"],
                        "type": table["type"],
                    },
                },
                message=(
                    f"Table updated: {old_table['name']} → {table['name']}"
                    if old_table
                    else f"Table updated: {table['name']}"
                ),
            )
        except Exception as e:
            print(f"[WARNING] Failed to create version for table update: {str(e)}")

        if old_table:
            await realtime_broadcast(
                project_id,
                {
                    "type": "table_edited",
                    "ts": datetime.now(timezone.utc).isoformat(),
                    "actor_id": str(current_user["id"]),
                    "table_before": {
                        "id": old_table["id"],
                        "name": old_table["name"],
                        "type": old_table["type"],
                    },
                    "table_after": {
                        "id": table["id"],
                        "name": table["name"],
                        "type": table["type"],
                    },
                },
            )

        return {"status": "success", "message": "Tabla actualizada exitosamente", "table": table}
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=make_error(ErrorCode.SCHEMA_OPERATION_FAILED),
        )


