/**
 * Utilidades para convertir ConnectorTable al formato TableWithColumns
 * que usan las vistas de mapping.
 *
 * Las connector tables NO se guardan en la BD local. Su estructura se lee
 * dinámicamente desde la BD externa al conectarse.
 */

import type { ConnectorTable } from '../types/db_connection_types';
import type { TableWithColumns, Column } from '../types/mapping-types';

const PLACEHOLDER_TIMESTAMP = new Date(0).toISOString();

/**
 * Convierte una ConnectorTable al formato TableWithColumns para que las vistas
 * de mapping puedan mostrarla junto a las tablas importadas.
 *
 * - id: pseudo-id `connector:${session_id}:${schema}:${name}`
 * - columns[].id: column_hash (SHA-256 del nombre)
 * - is_connector, table_hash, session_id: marcadores para crear mappings con hashes
 */
export function connectorTableToTableWithColumns(
  connectorTable: ConnectorTable
): TableWithColumns {
  const columns: Column[] = connectorTable.columns.map(col => ({
    id: col.column_hash,
    table_id: connectorTable.id,
    name: col.name,
    data_type: col.data_type,
    table_type: connectorTable.type,
    is_nullable: col.is_nullable,
    is_primary: col.is_primary_key,
    is_autogenerated: col.is_auto_increment,
    created_at: PLACEHOLDER_TIMESTAMP,
    updated_at: PLACEHOLDER_TIMESTAMP,
    column_hash: col.column_hash,
  }));

  return {
    id: connectorTable.id,
    project_id: '',  // No pertenece a un proyecto local
    name: connectorTable.name,
    type: connectorTable.type,
    created_at: PLACEHOLDER_TIMESTAMP,
    updated_at: PLACEHOLDER_TIMESTAMP,
    is_connector: true,
    table_hash: connectorTable.table_hash,
    session_id: connectorTable.session_id,
    columns,
  };
}

/**
 * Convierte todas las connector tables al formato TableWithColumns.
 */
export function connectorTablesToTableWithColumns(
  connectorTables: ConnectorTable[]
): TableWithColumns[] {
  return connectorTables.map(connectorTableToTableWithColumns);
}
