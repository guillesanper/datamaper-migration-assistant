"""
Modelo ORM para Columns

Este módulo contiene el modelo para columnas de metadata.

Características:
- Columnas asociadas a tablas (origen o destino)
- Soporte de encriptación con AES-256-GCM:
  - name (plaintext, nullable cuando está encriptado)
  - name_encrypted + name_nonce (cifrado)
  - data_type (plaintext, nullable cuando está encriptado)
  - data_type_encrypted + data_type_nonce (cifrado)
  - is_encrypted (flag booleano)
- Metadatos: is_nullable, is_primary, is_autogenerated
- Constraint UNIQUE(table_id, name)
- Check constraints para garantizar integridad

La lógica de cifrado/descifrado se maneja en la capa de servicio.
"""

import uuid

from sqlalchemy import (
    Boolean,
    CheckConstraint,
    Column,
    DateTime,
    ForeignKey,
    Index,
    String,
    Text,
    text,
)
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import relationship
from sqlalchemy.sql import func

from app.database.base import Base


class TableColumn(Base):
    """
    Columna de una tabla de metadata.

    Representa una columna física en una tabla de origen o destino.

    Campos encriptables:
    - name / name_encrypted + name_nonce
    - data_type / data_type_encrypted + data_type_nonce

    Metadatos:
    - is_nullable: Permite valores NULL
    - is_primary: Es parte de la Primary Key (deprecado, usar primary_key_constraints)
    - is_autogenerated: Se auto-genera (ej: SERIAL, UUID DEFAULT gen_random_uuid())
    - table_type: 'origin' o 'destination' (redundante con table.type para queries)

    Check constraints aseguran que existen name/data_type O sus versiones encriptadas.
    """

    __tablename__ = "columns"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)

    # Relación con tabla
    table_id = Column(
        UUID(as_uuid=True), ForeignKey("tables.id", ondelete="CASCADE"), nullable=False, index=True
    )

    # Nombre (plaintext, nullable cuando está encriptado)
    name = Column(String(255))

    # Campos de encriptación para nombre
    name_encrypted = Column(Text)
    name_nonce = Column(Text)

    # Tipo de dato (plaintext, nullable cuando está encriptado)
    data_type = Column(String(100))

    # Campos de encriptación para tipo de dato
    data_type_encrypted = Column(Text)
    data_type_nonce = Column(Text)

    # Flag de encriptación
    is_encrypted = Column(
        Boolean, default=False, server_default=text("false"), nullable=False, index=True
    )

    # Tipo de tabla (redundante con table.type, pero útil para queries)
    table_type = Column(String(50), nullable=False)  # 'origin' o 'destination'

    # Metadatos de la columna
    is_nullable = Column(Boolean, default=True, nullable=False)
    is_primary = Column(
        Boolean, default=False, nullable=False
    )  # Deprecado, usar primary_key_constraints
    is_autogenerated = Column(Boolean, default=False, nullable=False)

    # Timestamps
    created_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)
    updated_at = Column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now(), nullable=False
    )

    # Relationships
    table = relationship("Table", back_populates="columns")

    # Constraints e índices
    __table_args__ = (
        # Constraint UNIQUE: (table_id, name) - solo cuando no está encriptado
        Index(
            "uq_columns_table_name",
            "table_id",
            "name",
            unique=True,
            postgresql_where=(is_encrypted == False),
        ),
        # Check constraint: debe existir name O name_encrypted+nonce
        CheckConstraint(
            """
            (name IS NOT NULL AND (is_encrypted IS NULL OR is_encrypted = FALSE))
            OR
            (name_encrypted IS NOT NULL AND name_nonce IS NOT NULL AND is_encrypted = TRUE)
            """,
            name="check_column_name_or_encrypted",
        ),
        # Check constraint: debe existir data_type O data_type_encrypted+nonce
        CheckConstraint(
            """
            (data_type IS NOT NULL AND (is_encrypted IS NULL OR is_encrypted = FALSE))
            OR
            (data_type_encrypted IS NOT NULL AND data_type_nonce IS NOT NULL AND is_encrypted = TRUE)
            """,
            name="check_column_datatype_or_encrypted",
        ),
        # Índices para búsquedas
        Index("idx_columns_table_encrypted", "table_id", "is_encrypted"),
        Index("idx_columns_encrypted", "is_encrypted", postgresql_where=(is_encrypted == True)),
        Index(
            "idx_columns_primary", "table_id", "is_primary", postgresql_where=(is_primary == True)
        ),
    )

    def __repr__(self):
        display_name = self.name if not self.is_encrypted else "[ENCRYPTED]"
        display_type = self.data_type if not self.is_encrypted else "[ENCRYPTED]"
        return f"<TableColumn(id={self.id}, name='{display_name}', data_type='{display_type}', is_encrypted={self.is_encrypted})>"
