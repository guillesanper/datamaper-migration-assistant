-- Crear tabla de rate limiting con el nombre correcto
CREATE TABLE IF NOT EXISTS security_rate_limits (
    id SERIAL PRIMARY KEY,
    ip_address VARCHAR(255) NOT NULL,
    endpoint VARCHAR(255) NOT NULL,
    attempt_count INTEGER DEFAULT 1 NOT NULL,
    last_attempt TIMESTAMP NOT NULL,
    blocked_until TIMESTAMP,
    created_at TIMESTAMP DEFAULT (NOW() AT TIME ZONE 'UTC') NOT NULL,
    updated_at TIMESTAMP DEFAULT (NOW() AT TIME ZONE 'UTC') NOT NULL,
    
    -- Constraint para evitar duplicados
    CONSTRAINT unique_ip_endpoint UNIQUE (ip_address, endpoint)
);

-- Índices para optimizar las consultas de rate limiting
CREATE INDEX IF NOT EXISTS idx_security_rate_limits_ip 
    ON security_rate_limits(ip_address);

CREATE INDEX IF NOT EXISTS idx_security_rate_limits_endpoint 
    ON security_rate_limits(endpoint);

CREATE INDEX IF NOT EXISTS idx_security_rate_limits_blocked 
    ON security_rate_limits(blocked_until) 
    WHERE blocked_until IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_security_rate_limits_updated 
    ON security_rate_limits(updated_at);

-- Comentarios en las columnas para documentación
COMMENT ON TABLE security_rate_limits IS 'Tabla para control de rate limiting por IP y endpoint';
COMMENT ON COLUMN security_rate_limits.ip_address IS 'Hash de la dirección IP del cliente';
COMMENT ON COLUMN security_rate_limits.endpoint IS 'Endpoint de la API que está siendo limitado';
COMMENT ON COLUMN security_rate_limits.attempt_count IS 'Número de intentos dentro de la ventana de tiempo';
COMMENT ON COLUMN security_rate_limits.last_attempt IS 'Timestamp del último intento';
COMMENT ON COLUMN security_rate_limits.blocked_until IS 'Timestamp hasta el cual la IP está bloqueada';

-- Función para limpiar registros antiguos (opcional pero recomendada)
CREATE OR REPLACE FUNCTION cleanup_old_rate_limits()
RETURNS INTEGER AS $$
DECLARE
    deleted_count INTEGER;
BEGIN
    DELETE FROM security_rate_limits
    WHERE updated_at < NOW() - INTERVAL '7 days'
      AND (blocked_until IS NULL OR blocked_until < NOW());
    
    GET DIAGNOSTICS deleted_count = ROW_COUNT;
    RETURN deleted_count;
END;
$$ LANGUAGE plpgsql;

