// Base data types (expanded from 6 to 25+ types)
export type BaseDataType =
  // Text types
  | 'TEXT' | 'VARCHAR' | 'CHAR'
  // Integer types
  | 'SMALLINT' | 'INTEGER' | 'BIGINT'
  // Numeric types with precision
  | 'NUMERIC' | 'DECIMAL' | 'REAL' | 'FLOAT' | 'DOUBLE PRECISION'
  // Boolean
  | 'BOOLEAN'
  // Date/Time types
  | 'DATE' | 'DATETIME' | 'TIME' | 'TIMESTAMP' | 'TIMESTAMPTZ' | 'INTERVAL'
  // JSON types
  | 'JSON' | 'JSONB'
  // UUID
  | 'UUID'
  // Binary
  | 'BYTEA'
  // Network address types
  | 'INET' | 'MACADDR'
  // Array (generic)
  | 'ARRAY';

// Legacy type for backward compatibility
export type DataType = string; // Can be 'VARCHAR(255)', 'NUMERIC(10,2)', 'INTEGER', etc.

// Data type with parameters
export interface DataTypeDefinition {
  baseType: BaseDataType;
  parameters?: {
    length?: number;        // For VARCHAR(n), CHAR(n)
    precision?: number;     // For NUMERIC(p,s), DECIMAL(p,s)
    scale?: number;         // For NUMERIC(p,s), DECIMAL(p,s)
  };
  fullType: string;  // Complete type string: "VARCHAR(255)", "NUMERIC(10,2)", "INTEGER"
}

// Type validation result
export interface TypeValidationResult {
  is_safe: boolean;
  risk_level: 'safe' | 'warning' | 'danger';
  message: string;
  recommendation: string;
  old_type: string;
  new_type: string;
  requires_confirmation: boolean;
  requires_backup: boolean;
  affected_rows?: number;
  examples?: string[];
  column_name?: string;
  table_name?: string;
}

// Type suggestions for parametrized types
export interface TypeSuggestions {
  common_lengths?: number[];
  default_length?: number;
  common_configs?: Array<{
    precision: number;
    scale: number;
    description: string;
  }>;
  default?: {
    precision?: number;
    scale?: number;
  };
  description: string;
  requires: string[];
  range?: string;
  format?: string;
  values?: string[];
  precision?: string;
}

