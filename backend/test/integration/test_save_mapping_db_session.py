"""
Regression test: save_mapping endpoint must use SQLAlchemy ORM session for ORM calls.

Bug: save_mapping used a raw psycopg2 connection for all DB operations, but
     ORM functions like get_tables_by_project_orm require a SQLAlchemy Session.
     This caused: AttributeError: 'psycopg2.extensions.connection' has no attribute 'query'

Fix: save_mapping injects db_orm=Depends(get_db_session) and uses that single
     SQLAlchemy Session for both the ORM CRUD functions and its own SQL queries.
"""

import uuid

import pytest

from app.models.orm import Table, TableColumn

# ============================================================================
# FIXTURES
# ============================================================================


@pytest.fixture
def project_with_schema(db_session, test_project):
    """
    Project that already has origin and destination tables with columns,
    ready for mapping creation.
    """
    project_id = test_project["id"]

    # Create origin table
    origin_table = Table(
        id=uuid.uuid4(),
        project_id=project_id,
        name="origin_table_1",
        type="origin",
        is_encrypted=False,
    )
    db_session.add(origin_table)
    db_session.flush()

    # Create origin column
    origin_col = TableColumn(
        id=uuid.uuid4(),
        table_id=origin_table.id,
        name="col2",
        data_type="TEXT",
        table_type="origin",
        is_encrypted=False,
        is_nullable=True,
        is_primary=False,
        is_autogenerated=False,
    )
    db_session.add(origin_col)

    # Create destination table
    dest_table = Table(
        id=uuid.uuid4(),
        project_id=project_id,
        name="destination_table_5",
        type="destination",
        is_encrypted=False,
    )
    db_session.add(dest_table)
    db_session.flush()

    # Create destination column
    dest_col = TableColumn(
        id=uuid.uuid4(),
        table_id=dest_table.id,
        name="col2",
        data_type="TEXT",
        table_type="destination",
        is_encrypted=False,
        is_nullable=True,
        is_primary=False,
        is_autogenerated=False,
    )
    db_session.add(dest_col)
    db_session.commit()

    return {
        "project_id": project_id,
        "origin_table": "origin_table_1",
        "origin_column": "col2",
        "destination_table": "destination_table_5",
        "destination_column": "col2",
    }


