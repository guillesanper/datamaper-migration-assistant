// src/components/mapping/modals/ColumnModal.tsx
import React, { useState, useEffect } from 'react';
import { X, Columns, AlertCircle, AlertTriangle } from 'lucide-react';
import { useTranslation } from 'react-i18next';
import { mappingService } from '../../../services/mapping_service';
import { toast } from '../../../utils/toast';
import type { Column, CreateColumnData, UpdateColumnData, DataType, TypeValidationResult } from '../../../types/mapping-types';
import styles from '../../../styles/mapping/mapping.module.css';
import { DataTypeSelector } from '../DataTypeSelector';
import { typeValidationService } from '../../../services/type_validation_service';
import { Button } from '../../ui/button';

interface ColumnModalProps {
  isOpen: boolean;
  onClose: () => void;
  projectId: string;
  tableId: string;
  tableName: string;
  tableType: 'origin' | 'destination';
  column?: Column;
  onSuccess: () => void;
}

export const ColumnModal: React.FC<ColumnModalProps> = ({
  isOpen,
  onClose,
  projectId,
  tableId,
  tableName,
  tableType,
  column,
  onSuccess
}) => {
  const { t } = useTranslation(['mapping', 'common']);

  const [name, setName] = useState('');
  const [dataType, setDataType] = useState<DataType>('TEXT');
  const [isNullable, setIsNullable] = useState(true);
  const [isPrimary, setIsPrimary] = useState(false);
  const [isAutogenerated, setIsAutogenerated] = useState(false);
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [error, setError] = useState('');

  const [isValidatingType, setIsValidatingType] = useState(false);
  const [typeValidation, setTypeValidation] = useState<TypeValidationResult | null>(null);

  const isEditMode = !!column;
  const isOrigin = tableType === 'origin';

  useEffect(() => {
    if (column) {
      setName(column.name || '');
      setDataType(column.data_type || 'TEXT');
      setIsNullable(column.is_nullable);
      setIsPrimary(column.is_primary);
      setIsAutogenerated(column.is_autogenerated || false);
    } else {
      setName('');
      setDataType('TEXT');
      setIsNullable(true);
      setIsPrimary(false);
      setIsAutogenerated(false);
    }
    setError('');
  }, [column, isOpen]);

  const validateName = (value: string): string | null => {
    if (!value.trim()) {
      return t('columnModal.name.validation.required');
    }
    if (!/^[A-Za-z0-9_][A-Za-z0-9_]{0,62}$/.test(value)) {
      return t('columnModal.name.validation.format');
    }
    return null;
  };

  const handleDataTypeChange = async (newType: string) => {
    if (!isEditMode || !column || newType === column.data_type) {
      setDataType(newType);
      setTypeValidation(null);
      return;
    }

    setDataType(newType);

    setIsValidatingType(true);
    try {
      const validation = await typeValidationService.validateTypeChange(
        projectId,
        column.id,
        newType
      );

      setTypeValidation(validation);
    } catch (error) {
      console.error('Error validating type change:', error);
      toast.error(t('columnModal.typeError'));
    } finally {
      setIsValidatingType(false);
    }
  };

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setError('');

    const validationError = validateName(name);
    if (validationError) {
      setError(validationError);
      return;
    }

    setIsSubmitting(true);

    try {
      if (isEditMode && column) {
        const updateData: UpdateColumnData = {
          name: name.trim(),
          data_type: dataType,
          is_nullable: isNullable,
          is_primary: isPrimary,
          is_autogenerated: isOrigin ? false : isAutogenerated
        };
        await mappingService.updateColumn(projectId, column.id, updateData);
        toast.success(t('columnModal.toast.updated'));
      } else {
        const createData: CreateColumnData = {
          name: name.trim(),
          table_id: tableId,
          data_type: dataType,
          is_nullable: isNullable,
          is_primary: isPrimary,
          is_autogenerated: isOrigin ? false : isAutogenerated
        };
        await mappingService.createColumn(projectId, tableId, createData);
        toast.success(t('columnModal.toast.created'));
      }

      onSuccess();
      handleClose();
    } catch (err: unknown) {
      console.error('Error al guardar columna:', err);

      let errorMessage = t('columnModal.toast.error');

      const errObj = err as Record<string, unknown>;
      const responseData = (errObj.response as Record<string, unknown> | undefined)?.data as Record<string, unknown> | undefined;
      if (responseData?.detail) {
        const detail = responseData.detail;

        if (Array.isArray(detail)) {
          errorMessage = detail.map((e: Record<string, unknown>) => String(e.msg ?? e.message ?? '')).join(', ');
        } else if (typeof detail === 'string') {
          errorMessage = detail;
        } else if (typeof detail === 'object' && detail !== null && (detail as Record<string, unknown>).msg) {
          errorMessage = String((detail as Record<string, unknown>).msg);
        }
      } else if (err instanceof Error) {
        errorMessage = err.message;
      }

      setError(errorMessage);
      toast.error(errorMessage);
    } finally {
      setIsSubmitting(false);
    }
  };

  const handleClose = () => {
    setName('');
    setDataType('TEXT');
    setIsNullable(true);
    setIsPrimary(false);
    setIsAutogenerated(false);
    setError('');
    onClose();
  };

  if (!isOpen) return null;

  return (
    <div className={styles.modalOverlay}>
      <div className={styles.modalContent} style={{ maxWidth: '550px' }}>
        {/* Header */}
        <div className={styles.modalHeader}>
          <div className="flex items-center gap-2">
            <Columns className="w-5 h-5" />
            <h2 className={styles.modalTitle}>
              {isEditMode ? t('columnModal.editTitle') : t('columnModal.createTitle')}
            </h2>
          </div>
          <button onClick={handleClose} className={styles.modalCloseButton}>
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Content */}
        <form onSubmit={handleSubmit}>
          <div className={styles.modalBody}>
            {/* Tabla info */}
            <div className="bg-muted p-3 rounded-lg">
              <p className="text-sm">
                <span className="text-muted-foreground">{t('columnModal.tableLabel')}</span>{' '}
                <span className="font-medium">{tableName}</span>
                <span className={`ml-2 text-xs px-2 py-0.5 rounded ${
                  isOrigin ? 'bg-blue-100 text-blue-700 dark:bg-blue-900/30 dark:text-blue-400' :
                  'bg-green-100 text-green-700 dark:bg-green-900/30 dark:text-green-400'
                }`}>
                  {isOrigin ? t('columnModal.origin') : t('columnModal.dest')}
                </span>
              </p>
            </div>

            {/* Nombre */}
            <div>
              <label className="text-sm font-medium mb-2 block">
                {t('columnModal.name.label')} <span className="text-red-500">*</span>
              </label>
              <input
                type="text"
                value={name}
                onChange={(e) => {
                  setName(e.target.value);
                  setError('');
                }}
                placeholder={t('columnModal.name.placeholder')}
                className={`w-full px-3 py-2 border rounded-lg bg-background ${
                  error ? 'border-red-500' : 'border-border'
                } focus:outline-none focus:ring-2 focus:ring-primary`}
                disabled={isSubmitting}
                autoFocus
              />
            </div>

            {/* Tipo de Dato */}
            <div>
              <DataTypeSelector
                value={dataType}
                onChange={handleDataTypeChange}
                disabled={isSubmitting || isValidatingType}
                showDescription={true}
              />

              {isValidatingType && (
                <div className="mt-2 flex items-center gap-2 text-sm text-muted-foreground">
                  <div className="animate-spin rounded-full h-4 w-4 border-2 border-primary border-t-transparent" />
                  {t('columnModal.validatingType')}
                </div>
              )}

              {typeValidation && (
                <div className={`mt-2 p-3 rounded-lg border ${
                  typeValidation.risk_level === 'safe'
                    ? 'bg-green-50 border-green-200 dark:bg-green-950 dark:border-green-800'
                    : typeValidation.risk_level === 'warning'
                    ? 'bg-yellow-50 border-yellow-200 dark:bg-yellow-950 dark:border-yellow-800'
                    : 'bg-rose-50 border-rose-200 dark:bg-rose-950/50 dark:border-rose-800'
                }`}>
                  <div className="flex items-start gap-3">
                    <AlertTriangle className={`w-5 h-5 mt-0.5 flex-shrink-0 ${
                      typeValidation.risk_level === 'safe'
                        ? 'text-green-600 dark:text-green-500'
                        : typeValidation.risk_level === 'warning'
                        ? 'text-yellow-600 dark:text-yellow-500'
                        : 'text-rose-600 dark:text-rose-500'
                    }`} />
                    <div className="flex-1 space-y-2">
                      <div>
                        <p className={`text-sm font-semibold ${
                          typeValidation.risk_level === 'safe'
                            ? 'text-green-900 dark:text-green-200'
                            : typeValidation.risk_level === 'warning'
                            ? 'text-yellow-900 dark:text-yellow-200'
                            : 'text-rose-900 dark:text-rose-200'
                        }`}>
                          {typeValidation.message}
                        </p>
                        <p className="text-xs text-muted-foreground mt-1">
                          {typeValidation.recommendation}
                        </p>
                      </div>

                      {typeValidation.requires_confirmation && (
                        <div className="pt-2 border-t border-rose-200 dark:border-rose-800">
                          <p className="text-xs text-rose-800 dark:text-rose-300">
                            {t('columnModal.typeChangeRisk')}
                          </p>
                        </div>
                      )}
                    </div>
                  </div>
                </div>
              )}
            </div>

            {/* Opciones */}
            <div className="space-y-2">
              <label className="text-sm font-medium block mb-2">{t('columnModal.options.label')}</label>

              <label className="flex items-center gap-2 cursor-pointer p-2 rounded hover:bg-muted/50">
                <input
                  type="checkbox"
                  checked={isNullable}
                  onChange={(e) => setIsNullable(e.target.checked)}
                  className="w-4 h-4"
                  disabled={isSubmitting}
                />
                <div className="flex-1">
                  <span className="text-sm font-medium">{t('columnModal.nullable.label')}</span>
                  <p className="text-xs text-muted-foreground">{t('columnModal.nullable.hint')}</p>
                </div>
              </label>

              <label className="flex items-center gap-2 cursor-pointer p-2 rounded hover:bg-muted/50">
                <input
                  type="checkbox"
                  checked={isPrimary}
                  onChange={(e) => setIsPrimary(e.target.checked)}
                  className="w-4 h-4"
                  disabled={isSubmitting}
                />
                <div className="flex-1">
                  <span className="text-sm font-medium">{t('columnModal.pk.label')}</span>
                  <p className="text-xs text-muted-foreground">{t('columnModal.pk.hint')}</p>
                </div>
              </label>

              {!isOrigin && (
                <label className="flex items-center gap-2 cursor-pointer p-2 rounded hover:bg-muted/50">
                  <input
                    type="checkbox"
                    checked={isAutogenerated}
                    onChange={(e) => setIsAutogenerated(e.target.checked)}
                    className="w-4 h-4"
                    disabled={isSubmitting}
                  />
                  <div className="flex-1">
                    <span className="text-sm font-medium">{t('columnModal.autogenerated.label')}</span>
                    <p className="text-xs text-muted-foreground">
                      {t('columnModal.autogenerated.hint')}
                    </p>
                  </div>
                </label>
              )}
            </div>

            {/* Error message */}
            {error && (
              <div className={`${styles.alert} ${styles.alertInfo}`}>
                <div className={styles.alertContent}>
                  <AlertCircle className="w-4 h-4 text-red-500" />
                  <p className="text-sm text-red-600 dark:text-red-400">{error}</p>
                </div>
              </div>
            )}

            {/* Info sobre autogenerado */}
            {isOrigin && (
              <div className={`${styles.alert} ${styles.alertInfo}`}>
                <div className={styles.alertContent}>
                  <AlertCircle className={`${styles.alertIcon} ${styles.alertIconInfo}`} />
                  <div className={styles.alertBody}>
                    <p className="text-xs text-muted-foreground">
                      {t('columnModal.originNote')}
                    </p>
                  </div>
                </div>
              </div>
            )}
          </div>

          {/* Footer */}
          <div className={styles.modalFooter}>
            <div className={styles.modalFooterRight}>
              <Button
                type="button"
                variant="outline"
                onClick={handleClose}
                disabled={isSubmitting}
              >
                {t('common:actions.cancel')}
              </Button>
              <Button
                type="submit"
                disabled={isSubmitting || !name.trim()}
              >
                {isSubmitting ? (
                  <>
                    <div className="animate-spin rounded-full h-4 w-4 border-2 border-white border-t-transparent" />
                    {t('columnModal.savingBtn')}
                  </>
                ) : (
                  <>
                    <Columns className="w-4 h-4" />
                    {isEditMode ? t('columnModal.updateBtn') : t('columnModal.createBtn')}
                  </>
                )}
              </Button>
            </div>
          </div>
        </form>
      </div>
    </div>
  );
};
