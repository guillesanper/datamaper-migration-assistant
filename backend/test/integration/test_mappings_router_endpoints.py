@pytest.mark.integration
class TestImportStructure:
    def _post(self, client, project_id, tables=None, strategy="skip", **kwargs):
        return client.post(
            f"/api/mappings/projects/{project_id}/import_structure",
            files=kwargs.get("files") or _import_file(tables or IMPORT_TABLES),
            data={"format": "json", "duplicate_strategy": strategy},
        )

    def test_import_creates_tables_and_columns(
        self, authenticated_client, test_project, db_session
    ):
        r = self._post(authenticated_client, test_project["id"])
        assert r.status_code == 200, r.text
        body = r.json()
        assert body["status"] == "ok"
        assert body["tables_added"] == 2
        assert body["columns_added"] == 3
        db_session.expire_all()
        tables = db_session.query(Table).filter(Table.project_id == test_project["id"]).all()
        assert {(t.name, t.type) for t in tables} == {
            ("orders", "origin"),
            ("orders_dest", "destination"),
        }

    def test_import_bundled_origin_destination_example_is_accepted_whole(
        self, authenticated_client, test_project, db_session
    ):
        """El JSON de ejemplo que se entrega al usuario se importa entero, sin descartes."""
        example = json.loads(EXAMPLE_ORIGIN_DESTINATION.read_text(encoding="utf-8"))
        tables = example["tables"]
        assert {t["type"] for t in tables} == {"origin", "destination"}

        r = self._post(authenticated_client, test_project["id"], tables=tables)
        assert r.status_code == 200, r.text
        body = r.json()
        assert body["tables_added"] == len(tables)
        assert body["columns_added"] == sum(len(t["columns"]) for t in tables)
        assert body["total_in_file"] == len(tables)
        db_session.expire_all()
        saved = db_session.query(Table).filter(Table.project_id == test_project["id"]).all()
        assert {(t.name, t.type) for t in saved} == {(t["name"], t["type"]) for t in tables}

    def test_import_skip_strategy_does_not_duplicate(self, authenticated_client, test_project):
        assert self._post(authenticated_client, test_project["id"]).status_code == 200
        r = self._post(authenticated_client, test_project["id"])
        assert r.status_code == 200, r.text
        body = r.json()
        assert body["tables_added"] == 0
        assert body["tables_duplicates_skipped"] == 2
        assert body["duplicates_skipped"] == 3

    def test_import_replace_strategy_recreates_tables(
        self, authenticated_client, test_project, db_session
    ):
        assert self._post(authenticated_client, test_project["id"]).status_code == 200
        r = self._post(authenticated_client, test_project["id"], strategy="replace")
        assert r.status_code == 200, r.text
        body = r.json()
        assert body["tables_replaced"] == 2
        assert body["columns_replaced"] == 3
        assert body["tables_added"] == 2
        db_session.expire_all()
        assert db_session.query(Table).filter(Table.project_id == test_project["id"]).count() == 2

    def test_import_invalid_json_returns_400(self, authenticated_client, test_project):
        r = self._post(
            authenticated_client,
            test_project["id"],
            files={"file": ("tables.json", b"{no es json", "application/json")},
        )
        assert r.status_code == 400, r.text

    def _schema_error(self, client, project_id, mutate):
        """Importa IMPORT_TABLES tras mutarlo y devuelve el `detail` estructurado del 400."""
        tables = json.loads(json.dumps(IMPORT_TABLES))
        mutate(tables)
        r = self._post(client, project_id, tables=tables)
        assert r.status_code == 400, r.text
        detail = r.json()["detail"]
        assert isinstance(detail, dict), detail
        return detail

    def test_import_schema_missing_field_reports_field_and_location(
        self, authenticated_client, test_project
    ):
        detail = self._schema_error(
            authenticated_client,
            test_project["id"],
            lambda t: t[0]["columns"][1].pop("is_primary"),
        )
        assert detail["code"] == "mapping.import_missing_field"
        assert detail["params"]["field"] == "is_primary"
        assert detail["params"]["where"] == 'tables[0] ("orders") › columns[1] ("total")'

    def test_import_schema_unknown_field_reports_field_and_location(
        self, authenticated_client, test_project
    ):
        detail = self._schema_error(
            authenticated_client,
            test_project["id"],
            lambda t: t[1]["columns"][0].update(length=10),
        )
        assert detail["code"] == "mapping.import_unknown_field"
        assert detail["params"]["field"] == "length"
        assert detail["params"]["where"] == 'tables[1] ("orders_dest") › columns[0] ("order_id")'

    def test_import_schema_invalid_value_lists_allowed_values(
        self, authenticated_client, test_project
    ):
        detail = self._schema_error(
            authenticated_client,
            test_project["id"],
            lambda t: t[0]["columns"][0].update(type="VARCHAR"),
        )
        assert detail["code"] == "mapping.import_invalid_value"
        params = detail["params"]
        assert params["field"] == "type"
        assert params["value"] == "VARCHAR"
        assert "INTEGER" in params["allowed"]
        assert params["where"] == 'tables[0] ("orders") › columns[0] ("id")'

    def test_import_schema_other_violation_falls_back_to_generic_code(
        self, authenticated_client, test_project
    ):
        detail = self._schema_error(
            authenticated_client,
            test_project["id"],
            lambda t: t[0].update(columns=[]),
        )
        assert detail["code"] == "mapping.import_schema_invalid"
        assert detail["params"]["where"] == 'tables[0] ("orders") › columns'
        assert detail["params"]["reason"]

    def test_import_unknown_project_returns_404(self, authenticated_client):
        r = self._post(authenticated_client, uuid.uuid4())
        assert r.status_code == 404, r.text

    def test_import_foreign_project_returns_403(self, authenticated_client, foreign_project):
        r = self._post(authenticated_client, foreign_project)
        assert r.status_code == 403, r.text


