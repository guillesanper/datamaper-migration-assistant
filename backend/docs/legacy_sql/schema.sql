-- 1. Tabla de usuarios
CREATE TABLE users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    username VARCHAR(100) UNIQUE NOT NULL,
    email VARCHAR(255) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. Tabla de proyectos
CREATE TABLE projects (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name VARCHAR(255) NOT NULL,
    origin_db VARCHAR(255),
    destination_db VARCHAR(255),
    owner_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 3. Miembros de proyectos
CREATE TABLE project_members (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    project_id UUID NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role VARCHAR(50) NOT NULL, -- 'editor', 'viewer', etc.
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(project_id, user_id)
);

-- 4. Tabla de tablas (meta-tabla para origen/destino)
CREATE TABLE tables (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    project_id UUID NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    type VARCHAR(50) NOT NULL, -- 'origin' o 'destination'
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(project_id, name, type)
);

-- 5. Columnas de las tablas
CREATE TABLE columns (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    table_id UUID NOT NULL REFERENCES tables(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    data_type VARCHAR(100) NOT NULL,
    table_type VARCHAR(50) NOT NULL, -- 'origin' o 'destination'
    is_nullable BOOLEAN DEFAULT TRUE,
    is_primary BOOLEAN DEFAULT FALSE,
    is_autogenerated BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(table_id, name)
);

-- 6. Mapeos entre columnas
CREATE TABLE mappings (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    project_id UUID NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    origin_table VARCHAR(255) NOT NULL,
    origin_column VARCHAR(255) NOT NULL,
    destination_table VARCHAR(255) NOT NULL,
    destination_column VARCHAR(255) NOT NULL,
    transformation_logic TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 7. Planes de suscripción
CREATE TABLE subscription_plans (
    id VARCHAR(50) PRIMARY KEY, -- 'free', 'pro', etc.
    name VARCHAR(100) NOT NULL,
    description TEXT,
    price_monthly DECIMAL(10,2),
    price_yearly DECIMAL(10,2),
    currency VARCHAR(3) DEFAULT 'USD',
    features JSONB,
    max_projects INTEGER,
    max_tables INTEGER,
    max_columns_per_table INTEGER,
    stripe_product_id VARCHAR(255),
    stripe_price_id_monthly VARCHAR(255),
    stripe_price_id_yearly VARCHAR(255),
    stripe_secret_key VARCHAR(500),
    stripe_publishable_key VARCHAR(500),
    stripe_webhook_secret VARCHAR(500),
    is_active BOOLEAN DEFAULT TRUE,
    sort_order INTEGER DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 8. Suscripciones de usuarios
CREATE TABLE subscriptions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    project_id UUID NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    stripe_customer_id VARCHAR(255),
    stripe_subscription_id VARCHAR(255) UNIQUE,
    plan_id VARCHAR(50) NOT NULL REFERENCES subscription_plans(id),
    price_id VARCHAR(255),
    status VARCHAR(50), -- 'active', 'trialing', 'canceled', etc.
    current_period_start TIMESTAMP,
    current_period_end TIMESTAMP,
    cancel_at_period_end BOOLEAN DEFAULT FALSE,
    cancel_at TIMESTAMP,
    trial_end TIMESTAMP,
    currency VARCHAR(3),
    unit_amount INTEGER,
    quantity INTEGER DEFAULT 1,
    default_payment_method VARCHAR(255),
    latest_invoice_id VARCHAR(255),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Índices para mejorar el rendimiento
CREATE INDEX idx_projects_owner ON projects(owner_id);
CREATE INDEX idx_project_members_project ON project_members(project_id);
CREATE INDEX idx_project_members_user ON project_members(user_id);
CREATE INDEX idx_tables_project ON tables(project_id);
CREATE INDEX idx_columns_table ON columns(table_id);
CREATE INDEX idx_mappings_project ON mappings(project_id);
CREATE INDEX idx_subscriptions_user ON subscriptions(user_id);
CREATE INDEX idx_subscriptions_project ON subscriptions(project_id);
CREATE INDEX idx_subscriptions_stripe ON subscriptions(stripe_subscription_id);

-- Tabla de logs de seguridad
CREATE TABLE IF NOT EXISTS security_logs (
    id BIGSERIAL PRIMARY KEY,
    event_type VARCHAR(100) NOT NULL,
    ip_address VARCHAR(64),
    username VARCHAR(100),
    user_id UUID,
    endpoint VARCHAR(255),
    details JSONB,
    severity VARCHAR(20) DEFAULT 'info',
    created_at TIMESTAMP NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC'),
    
    -- Índices para búsquedas rápidas
    CONSTRAINT fk_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
);

-- Índices para mejorar performance de consultas
CREATE INDEX IF NOT EXISTS idx_security_logs_event_type ON security_logs(event_type);
CREATE INDEX IF NOT EXISTS idx_security_logs_username ON security_logs(username);
CREATE INDEX IF NOT EXISTS idx_security_logs_user_id ON security_logs(user_id);
CREATE INDEX IF NOT EXISTS idx_security_logs_ip_address ON security_logs(ip_address);
CREATE INDEX IF NOT EXISTS idx_security_logs_severity ON security_logs(severity);
CREATE INDEX IF NOT EXISTS idx_security_logs_created_at ON security_logs(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_security_logs_endpoint ON security_logs(endpoint);

-- Índice para búsquedas en el JSON details
CREATE INDEX IF NOT EXISTS idx_security_logs_details ON security_logs USING GIN (details);

-- Comentarios para documentación
COMMENT ON TABLE security_logs IS 'Registro de eventos de seguridad del sistema';
COMMENT ON COLUMN security_logs.event_type IS 'Tipo de evento (login_success, login_failed, etc.)';
COMMENT ON COLUMN security_logs.ip_address IS 'IP hasheada del cliente';
COMMENT ON COLUMN security_logs.details IS 'Detalles adicionales del evento en formato JSON';
COMMENT ON COLUMN security_logs.severity IS 'Severidad: info, warning, error, critical';

-- Tabla para rate limiting
CREATE TABLE IF NOT EXISTS security_rate_limits (
    id BIGSERIAL PRIMARY KEY,
    identifier VARCHAR(255) NOT NULL,  -- IP, user_id, email, etc.
    endpoint VARCHAR(255) NOT NULL,
    request_count INTEGER DEFAULT 1,
    window_start TIMESTAMP NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC'),
    created_at TIMESTAMP NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC'),
    updated_at TIMESTAMP NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC'),
    
    -- Índice único para evitar duplicados en la misma ventana
    UNIQUE(identifier, endpoint, window_start)
);

-- Índices para mejorar el rendimiento
CREATE INDEX IF NOT EXISTS idx_rate_limits_identifier ON security_rate_limits(identifier);
CREATE INDEX IF NOT EXISTS idx_rate_limits_endpoint ON security_rate_limits(endpoint);
CREATE INDEX IF NOT EXISTS idx_rate_limits_window ON security_rate_limits(window_start);

-- Comentarios
COMMENT ON TABLE security_rate_limits IS 'Control de rate limiting por endpoint y identificador';
COMMENT ON COLUMN security_rate_limits.identifier IS 'Identificador único (IP, email, user_id)';
COMMENT ON COLUMN security_rate_limits.endpoint IS 'Endpoint al que se aplica el rate limit';
COMMENT ON COLUMN security_rate_limits.request_count IS 'Número de peticiones en la ventana actual';
COMMENT ON COLUMN security_rate_limits.window_start IS 'Inicio de la ventana de tiempo';


